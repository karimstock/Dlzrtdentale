// UTILITY: Get site config by name
// =============================================

function getSiteByName(name) {
  const normalized = name.toLowerCase().replace(/[^a-z0-9-]/g, '');
  return SITES.find(s =>
    s.name === normalized ||
    s.name === name ||
    s.baseUrl.includes(name) ||
    s.name.replace(/-/g, '') === normalized.replace(/-/g, '')
  );
}

function getAllSites() {
  return SITES;
}

function getSiteNames() {
  return SITES.map(s => s.name);
}

function getSitesByType(type) {
  return SITES.filter(s => s.type === type);
}

function getSitesByAntiBotLevel(level) {
  return SITES.filter(s => (s.antiBotLevel || 'none') === level);
}

